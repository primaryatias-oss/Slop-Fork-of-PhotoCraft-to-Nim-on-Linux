## Synthetic CMYK output profiles.
##
## PhotoCraft ships a CMYK profile it generates itself from a documented printer model:
## Yule–Nielsen modified Neugebauer (n = 2) over the 16 ink overprints with Demichel weights and
## parabolic dot gain; ISO 12647-2 coated-paper Lab aims for the K-free primaries; GCR black
## generation and a bounded least-squares CMY solve for the BToA tables; perceptual tables
## compress into a gamut boundary descriptor first. Plausible for coated offset, not a measured
## characterisation.

import std/[math, options]
import ./curve, ./clut, ./math as cmath, ./pipeline, ./profile, ./write

const Description* = "Photocraft Coated CMYK (synthetic, 300% TAC, medium GCR)"
const Copyright* = "No copyright: CC0-1.0 public domain dedication. Generated by photocraft-cms."

type
  CmykParams* = object
    description*: string
    tac*: float64         ## Total area coverage limit (3.0 = 300 %).
    gcrStart*: float64
    kMax*: float64
    gcrGamma*: float64
    tvi*: array[4, float64]
    gridA2b*, gridB2a*: int

  CmykModel* = object
    primN: array[16, Vec3]
    paper*: Vec3
    tvi: array[4, float64]

const YN = 2.0

proc defaultCmykParams*(): CmykParams =
  CmykParams(description: Description, tac: 3.0, gcrStart: 0.2, kMax: 0.95, gcrGamma: 1.1,
             tvi: [0.14, 0.14, 0.14, 0.17], gridA2b: 11, gridB2a: 21)

proc coatedModel*(tvi: array[4, float64]): CmykModel =
  proc lab(l, a, b: float64): Vec3 = labToXyz([l, a, b], D50)
  let w = lab(95.0, 0.0, -2.0)
  let base = [w, lab(55.0, -37.0, -50.0), lab(48.0, 74.0, -3.0), lab(24.0, 22.0, -46.0),
              lab(89.0, -5.0, 93.0), lab(50.0, -65.0, 27.0), lab(47.0, 68.0, 48.0), lab(23.0, 0.0, 0.0)]
  let k = lab(16.0, 0.0, 0.0)
  const floor = 0.006
  var prim: array[16, Vec3]
  for m in 0 ..< 16:
    let p = base[m and 7]
    if (m and 8) == 0: prim[m] = p
    else:
      for i in 0..2:
        let s = floor * w[i]
        prim[m][i] = s + (p[i] - s) * (k[i] - s) / (w[i] - s)
  for m in 0 ..< 16:
    for i in 0..2: result.primN[m][i] = pow(max(prim[m][i], 0.0), 1.0 / YN)
  result.paper = w
  result.tvi = tvi

proc xyz*(model: CmykModel; cmyk: array[4, float64]): Vec3 =
  var a: array[4, float64]
  for i in 0..3:
    let v = clamp(cmyk[i], 0.0, 1.0)
    a[i] = clamp(v + 4.0 * model.tvi[i] * v * (1.0 - v), 0.0, 1.0)
  var s: Vec3
  for m in 0 ..< 16:
    var w = 1.0
    for i in 0..3: w *= (if (m and (1 shl i)) != 0: a[i] else: 1.0 - a[i])
    if w == 0.0: continue
    for i in 0..2: s[i] += w * model.primN[m][i]
  [pow(s[0], YN), pow(s[1], YN), pow(s[2], YN)]

proc lab*(model: CmykModel; cmyk: array[4, float64]): Vec3 =
  ## ICC-relative Lab (paper = L* 100).
  let x = model.xyz(cmyk)
  let rel = [x[0] * D50[0] / model.paper[0], x[1] * D50[1] / model.paper[1], x[2] * D50[2] / model.paper[2]]
  xyzToLab(rel, D50)

proc solveCmy(model: CmykModel; target: Vec3; k, limit: float64; seeds: seq[Vec3]): (Vec3, float64) =
  ## Bounded least-squares solve for C, M, Y given K (projected Levenberg–Marquardt).
  proc project(x0: Vec3): Vec3 =
    var x = x0
    for _ in 0..3:
      for v in x.mitems: v = clamp(v, 0.0, 1.0)
      let s = x[0] + x[1] + x[2]
      if s <= limit + 1e-12: break
      var active = 0
      for v in x:
        if v > 0.0: inc active
      let d = (s - limit) / float64(max(active, 1))
      for v in x.mitems:
        if v > 0.0: v -= d
    x
  proc err(x: Vec3): Vec3 =
    let l = model.lab([x[0], x[1], x[2], k])
    [l[0] - target[0], l[1] - target[1], l[2] - target[2]]
  proc norm2(e: Vec3): float64 = e[0] * e[0] + e[1] * e[1] + e[2] * e[2]
  var best = ([0.0, 0.0, 0.0], Inf)
  for seed in seeds:
    var x = project(seed)
    var e = err(x)
    var f = norm2(e)
    var lambda = 1e-3
    for _ in 0 ..< 60:
      const h = 1e-5
      var j: Mat3
      for c in 0..2:
        var xp = x
        xp[c] += h
        let ep = err(xp)
        for r in 0..2: j[r][c] = (ep[r] - e[r]) / h
      var a: Mat3
      var g: Vec3
      for r in 0..2:
        for c in 0..2:
          var acc = 0.0
          for kk in 0..2: acc += j[kk][r] * j[kk][c]
          a[r][c] = acc
        var acc = 0.0
        for kk in 0..2: acc += j[kk][r] * e[kk]
        g[r] = -acc
      var improved = false
      for _ in 0 ..< 8:
        var al = a
        for d in 0..2: al[d][d] += lambda * (1.0 + a[d][d])
        let inv = invert(al)
        if inv.isNone:
          lambda *= 10.0
          continue
        let step = apply(inv.get, g)
        let xn = project([x[0] + step[0], x[1] + step[1], x[2] + step[2]])
        let en = err(xn)
        let fnew = norm2(en)
        if fnew < f:
          var moved = 0.0
          for i in 0..2: moved = max(moved, abs(xn[i] - x[i]))
          x = xn
          e = en
          f = fnew
          lambda = max(lambda * 0.3, 1e-9)
          improved = moved > 1e-9
          break
        lambda *= 10.0
      if not improved or f < 1e-10: break
    if f < best[1]: best = (x, f)
    if best[1] < 1e-6: break
  (best[0], sqrt(best[1]))

const Seeds: array[5, Vec3] = [[0.3, 0.3, 0.3], [0.05, 0.05, 0.05], [0.8, 0.8, 0.8], [0.9, 0.2, 0.2], [0.2, 0.9, 0.9]]

proc separate*(model: CmykModel; p: CmykParams; target: Vec3; warm: Option[array[4, float64]]): (array[4, float64], float64) =
  ## Colorimetric separation of a relative Lab target: GCR black generation then a CMY solve.
  var seeds: seq[Vec3]
  if warm.isSome: seeds.add [warm.get[0], warm.get[1], warm.get[2]]
  for s in Seeds: seeds.add s
  let (cmy0, _) = solveCmy(model, target, 0.0, 3.0, seeds)
  let g = min(cmy0[0], min(cmy0[1], cmy0[2]))
  let k = if g <= p.gcrStart: 0.0 else: p.kMax * pow((g - p.gcrStart) / (1.0 - p.gcrStart), p.gcrGamma)
  var seeds2 = @[[max(cmy0[0] - k, 0.0), max(cmy0[1] - k, 0.0), max(cmy0[2] - k, 0.0)], cmy0]
  seeds2.add seeds
  let (cmy, de) = solveCmy(model, target, k, max(p.tac - k, 0.0), seeds2)
  ([cmy[0], cmy[1], cmy[2], k], de)

type Gbd = object
  lBins, hBins: int
  cmax: seq[float64]
  blackL: float64

proc newGbd(model: CmykModel; p: CmykParams): Gbd =
  let lBins = 41
  let hBins = 72
  var cmax = newSeq[float64](lBins * hBins)
  const n = 21
  var blackL = 100.0
  for ci in 0 ..< n:
    for mi in 0 ..< n:
      for yi in 0 ..< n:
        for ki in 0 ..< 11:
          let v = [float64(ci) / (n - 1), float64(mi) / (n - 1), float64(yi) / (n - 1), float64(ki) / 10.0]
          if v[0] + v[1] + v[2] + v[3] > p.tac + 1e-9: continue
          let lab = model.lab(v)
          blackL = min(blackL, lab[0])
          let c = hypot(lab[1], lab[2])
          var h = arctan2(lab[2], lab[1])
          if h < 0: h += TAU
          let li = int(clamp(round((lab[0] / 100.0) * float64(lBins - 1)), 0.0, float64(lBins - 1)))
          let hi = int(round((h / TAU) * float64(hBins))) mod hBins
          cmax[li * hBins + hi] = max(cmax[li * hBins + hi], c)
  proc get(v: seq[float64]; l, h: int): float64 =
    let ll = clamp(l, 0, lBins - 1)
    var hh = h mod hBins
    if hh < 0: hh += hBins
    v[ll * hBins + hh]
  var filled = cmax
  for l in 0 ..< lBins:
    for h in 0 ..< hBins:
      var m = 0.0
      for dl in -1..1:
        for dh in -1..1: m = max(m, get(cmax, l + dl, h + dh))
      filled[l * hBins + h] = m
  var smooth = filled
  for l in 0 ..< lBins:
    for h in 0 ..< hBins:
      var s = 0.0
      for dl in -1..1:
        for dh in -1..1: s += get(filled, l + dl, h + dh)
      smooth[l * hBins + h] = s / 9.0
  Gbd(lBins: lBins, hBins: hBins, cmax: smooth, blackL: blackL)

proc maxChroma(g: Gbd; l, h: float64): float64 =
  let lp = clamp(l / 100.0, 0.0, 1.0) * float64(g.lBins - 1)
  var hr = h mod TAU
  if hr < 0: hr += TAU
  let hp = (hr / TAU) * float64(g.hBins)
  let l0 = int(floor(lp))
  let h0 = int(floor(hp))
  let fl = lp - float64(l0)
  let fh = hp - float64(h0)
  let l1 = min(l0 + 1, g.lBins - 1)
  let h0m = h0 mod g.hBins
  let h1m = (h0 + 1) mod g.hBins
  proc v(l, h: int): float64 = g.cmax[l * g.hBins + h]
  let a = v(l0, h0m) + (v(l0, h1m) - v(l0, h0m)) * fh
  let b = v(l1, h0m) + (v(l1, h1m) - v(l1, h0m)) * fh
  a + (b - a) * fl

proc compress(g: Gbd; lab: Vec3): Vec3 =
  let l = g.blackL + clamp(lab[0], 0.0, 100.0) * (100.0 - g.blackL) / 100.0
  let c = hypot(lab[1], lab[2])
  if c < 1e-9: return [l, 0.0, 0.0]
  let h = arctan2(lab[2], lab[1])
  let cm = max(g.maxChroma(l, h), 1e-3)
  let knee = 0.8 * cm
  let c2 = if c <= knee: c else: knee + (cm - knee) * tanh((c - knee) / (cm - knee))
  [l, c2 * cos(h), c2 * sin(h)]

proc decodeV2(v: Vec3): Vec3 =
  [v[0] * 100.0 * 65535.0 / 65280.0, v[1] * 65535.0 / 256.0 - 128.0, v[2] * 65535.0 / 256.0 - 128.0]

proc encodeV2(lab: Vec3): array[3, float32] =
  [float32(clamp(lab[0] / (100.0 * 65535.0 / 65280.0), 0.0, 1.0)),
   float32(clamp((lab[1] + 128.0) * 256.0 / 65535.0, 0.0, 1.0)),
   float32(clamp((lab[2] + 128.0) * 256.0 / 65535.0, 0.0, 1.0))]

proc b2aTable(model: CmykModel; p: CmykParams; gbd: Option[Gbd]): Clut =
  let n = p.gridB2a
  var data = newSeqOfCap[float32](n * n * n * 4)
  for row in 0 ..< n * n:
    let li = row div n
    let ai = row mod n
    var warm = none(array[4, float64])
    for bi in 0 ..< n:
      let lab = decodeV2([float64(li) / float64(n - 1), float64(ai) / float64(n - 1), float64(bi) / float64(n - 1)])
      let target = if gbd.isSome: gbd.get.compress(lab) else: lab
      let (cmyk, _) = separate(model, p, target, warm)
      warm = some(cmyk)
      for v in cmyk: data.add float32(v)
  newClut(@[n, n, n], 4, data)

proc lut16(c: Clut): Lut =
  var ic, oc: seq[Curve]
  for _ in 0 ..< c.inputs: ic.add tableCurve(@[0.0'f32, 1.0])
  for _ in 0 ..< c.outputs: oc.add tableCurve(@[0.0'f32, 1.0])
  Lut(kind: lkLut16, inputs: c.inputs, outputs: c.outputs, stages: @[curvesStage(ic), clutStage(c), curvesStage(oc)])

proc cmykProfile*(p: CmykParams): Profile =
  ## Generates a synthetic CMYK profile (slow: tens of seconds).
  let model = coatedModel(p.tvi)
  let g = p.gridA2b
  let a2bClut = sampleClut(@[g, g, g, g], 3, proc(inp: openArray[float32]; outp: var openArray[float32]) =
    let e = encodeV2(model.lab([float64(inp[0]), float64(inp[1]), float64(inp[2]), float64(inp[3])]))
    for k in 0..2: outp[k] = e[k])
  let gbd = newGbd(model, p)
  let colorimetric = b2aTable(model, p, none(Gbd))
  let perceptual = b2aTable(model, p, some(gbd))
  let a2b = lut16(a2bClut)
  let b0 = lut16(perceptual)
  let b1 = lut16(colorimetric)
  Profile(version: (4'u8, 0x30'u8), class: profileClass(pcOutput), colorSpace: colorSpace(csCmyk), pcs: pcsLab,
          renderingIntent: Perceptual, description: p.description, copyright: Copyright,
          whitePoint: [s15f16Round(model.paper[0]), s15f16Round(model.paper[1]), s15f16Round(model.paper[2])],
          a2b: [some(a2b), some(a2b), some(a2b)], b2a: [some(b0), some(b1), some(b0)]).withEncodedBytes

proc coatedCmyk*(): Profile = cmykProfile(defaultCmykParams())
