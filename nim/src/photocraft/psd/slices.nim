## Slices image resource (id 1050). Version 6 is a fixed binary layout, optionally followed by a
## versioned descriptor with per-slice extras (outsets); versions 7 and 8 are one descriptor.
## Writing produces version 6 (or the version 7 descriptor form with `toDescriptorBytes`).

import std/options
import ./io, ./descriptor

const SlicesId* = 1050'u16

type
  SliceRecord* = object
    id*, groupId*, origin*: uint32  ## origin: 0 auto, 1 layer-based, 2 user
    layerId*: Option[uint32]
    name*: string
    kind*: uint32                   ## 0 no image, 1 image, 2 table
    rect*: array[4, int32]          ## left, top, right, bottom
    url*, target*, message*, alt*: string
    cellTextIsHtml*: bool
    cellText*: string
    horizontalAlign*, verticalAlign*: uint32
    color*: array[4, uint8]         ## alpha, red, green, blue
    outsets*: array[4, int32]       ## top, left, bottom, right
  SlicesResource* = object
    version*: uint32
    bounds*: array[4, int32]        ## top, left, bottom, right
    groupName*: string
    slices*: seq[SliceRecord]

proc ustrR(r: var Reader): string = $readUstr(r)
proc putUstr(o: var seq[byte]; s: string) = ustr(s).write(o)

proc dInt(d: Descriptor; k: string): Option[int64] =
  let v = d.getDouble(k)
  if v.isSome: some(int64(v.get)) else: none(int64)

proc dBounds(d: Descriptor; k: string): Option[array[4, int32]] =
  let b = d.getDesc(k)
  if b.isNone: return
  template g(key: string): int32 = int32(b.get.dInt(key).get(0))
  some([g("Top "), g("Left"), g("Btom"), g("Rght")])

proc sliceFromDescriptor(d: Descriptor): SliceRecord =
  let b = d.dBounds("bounds").get([0'i32, 0, 0, 0])
  var color: array[4, uint8]
  let bgc = d.getDesc("bgColor")
  if d.getEnum("bgColorType") == some("Clr ") and bgc.isSome:
    let c = bgc.get
    template g(k: string): uint8 = uint8(clamp(c.dInt(k).get(0), 0, 255))
    color = [(if c.get("alpha").isSome: g("alpha") else: 255'u8), g("Rd  "), g("Grn "), g("Bl  ")]
  let origin = d.getEnum("origin")
  let kind = d.getEnum("Type")
  result = SliceRecord(id: uint32(d.dInt("sliceID").get(0)), groupId: uint32(d.dInt("groupID").get(0)),
    origin: (if origin.isNone: 2'u32 elif origin.get == "autoGenerated": 0'u32
             elif origin.get in ["layerGenerated", "layer"]: 1'u32 else: 2'u32),
    name: d.getText("Nm  ").get(""),
    kind: (if kind.isNone: 1'u32 elif kind.get == "noImage": 0'u32 elif kind.get in ["Tbl ", "table"]: 2'u32 else: 1'u32),
    rect: [b[1], b[0], b[3], b[2]],
    url: d.getText("url").get(""), target: d.getText("null").get(""), message: d.getText("Msge").get(""),
    alt: d.getText("altTag").get(""), cellTextIsHtml: d.getBool("cellTextIsHTML").get(false),
    cellText: d.getText("cellText").get(""), color: color,
    outsets: [int32(d.dInt("topOutset").get(0)), int32(d.dInt("leftOutset").get(0)),
              int32(d.dInt("bottomOutset").get(0)), int32(d.dInt("rightOutset").get(0))])
  let lid = d.dInt("layerID")
  if lid.isSome: result.layerId = some(uint32(lid.get))

proc boundsDescriptor(tlbr: array[4, int32]): Value =
  vDesc(newDescriptor("Rct1").with("Top ", vInt(tlbr[0])).with("Left", vInt(tlbr[1]))
    .with("Btom", vInt(tlbr[2])).with("Rght", vInt(tlbr[3])))

proc parseSlices*(data: openArray[byte]): SlicesResource =
  var r = newReader(data)
  let version = r.u32()
  case version
  of 6:
    result.version = 6
    for k in 0..3: result.bounds[k] = r.i32()
    result.groupName = ustrR(r)
    let n = int(r.u32())
    if n > r.remaining div 16: raise invalid("slice count exceeds the resource size")
    for _ in 0 ..< n:
      var s: SliceRecord
      s.id = r.u32(); s.groupId = r.u32(); s.origin = r.u32()
      if s.origin == 1: s.layerId = some(r.u32())
      s.name = ustrR(r)
      s.kind = r.u32()
      for k in 0..3: s.rect[k] = r.i32()
      s.url = ustrR(r); s.target = ustrR(r); s.message = ustrR(r); s.alt = ustrR(r)
      s.cellTextIsHtml = r.u8() != 0
      s.cellText = ustrR(r)
      s.horizontalAlign = r.u32(); s.verticalAlign = r.u32()
      for k in 0..3: s.color[k] = r.u8()
      result.slices.add s
    if r.remaining >= 4:
      try:
        let vd = readVersioned(r)
        for v in vd.descriptor.getList("slices").get(@[]):
          if v.kind != vkDescriptor: continue
          let extra = sliceFromDescriptor(v.desc)
          for s in result.slices.mitems:
            if s.id == extra.id:
              s.outsets = extra.outsets
              break
      except PsdError: discard
  of 7, 8:
    let vd = readVersioned(r)
    let d = vd.descriptor
    result.version = version
    result.bounds = d.dBounds("bounds").get([0'i32, 0, 0, 0])
    result.groupName = d.getText("baseName").get("")
    for v in d.getList("slices").get(@[]):
      if v.kind == vkDescriptor: result.slices.add sliceFromDescriptor(v.desc)
  else: raise invalid("unsupported slices resource version " & $version)

proc toBytes*(x: SlicesResource): seq[byte] =
  result.putU32(6)
  for v in x.bounds: result.putI32(v)
  result.putUstr(x.groupName)
  result.putU32(uint32(x.slices.len))
  var anyOutset = false
  for s in x.slices:
    result.putU32(s.id); result.putU32(s.groupId); result.putU32(s.origin)
    if s.origin == 1: result.putU32(s.layerId.get(0))
    result.putUstr(s.name)
    result.putU32(s.kind)
    for v in s.rect: result.putI32(v)
    result.putUstr(s.url); result.putUstr(s.target); result.putUstr(s.message); result.putUstr(s.alt)
    result.putU8(if s.cellTextIsHtml: 1 else: 0)
    result.putUstr(s.cellText)
    result.putU32(s.horizontalAlign); result.putU32(s.verticalAlign)
    result.put(s.color)
    if s.outsets != [0'i32, 0, 0, 0]: anyOutset = true
  if anyOutset:
    var list: seq[Value]
    for s in x.slices:
      list.add vDesc(newDescriptor("slice").with("sliceID", vInt(int32(s.id))).with("topOutset", vInt(s.outsets[0]))
        .with("leftOutset", vInt(s.outsets[1])).with("bottomOutset", vInt(s.outsets[2])).with("rightOutset", vInt(s.outsets[3])))
    versioned(newDescriptor("null").with("slices", vList(list))).write(result)

proc toDescriptorBytes*(x: SlicesResource): seq[byte] =
  var list: seq[Value]
  for s in x.slices:
    let origin = case s.origin
      of 0: "autoGenerated"
      of 1: "layerGenerated"
      else: "userGenerated"
    let kind = case s.kind
      of 0: "noImage"
      of 2: "Tbl "
      else: "Img "
    var d = newDescriptor("slice").with("sliceID", vInt(int32(s.id))).with("groupID", vInt(int32(s.groupId)))
      .with("origin", vEnum("ESliceOrigin", origin))
    if s.origin == 1 and s.layerId.isSome: d = d.with("layerID", vInt(int32(s.layerId.get)))
    template t(v: string): Value = Value(kind: vkText, text: ustr(v))
    d = d.with("Nm  ", t(s.name)).with("Type", vEnum("ESliceType", kind))
      .with("bounds", boundsDescriptor([s.rect[1], s.rect[0], s.rect[3], s.rect[2]]))
      .with("url", t(s.url)).with("null", t(s.target)).with("Msge", t(s.message)).with("altTag", t(s.alt))
      .with("cellTextIsHTML", vBool(s.cellTextIsHtml)).with("cellText", t(s.cellText))
      .with("horzAlign", vEnum("ESliceHorzAlign", "default")).with("vertAlign", vEnum("ESliceVertAlign", "default"))
      .with("bgColorType", vEnum("ESliceBGColorType", "None"))
      .with("topOutset", vInt(s.outsets[0])).with("leftOutset", vInt(s.outsets[1]))
      .with("bottomOutset", vInt(s.outsets[2])).with("rightOutset", vInt(s.outsets[3]))
    list.add vDesc(d)
  let d = newDescriptor("null").with("bounds", boundsDescriptor(x.bounds)).with("slices", vList(list))
    .with("baseName", Value(kind: vkText, text: ustr(x.groupName)))
  result.putU32(7)
  versioned(d).write(result)
