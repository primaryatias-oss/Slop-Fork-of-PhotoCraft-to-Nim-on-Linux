## Generates `src/photocraft/text/ucd_data.nim`: the Unicode character properties the type engine
## needs (line breaking, grapheme clusters, scripts, bidi, normalization), from the Unicode
## Character Database as packaged with Perl (`unicore`, Unicode 15.0; any Linux system has it).
##
##   nim r tools/ucdgen.nim [/usr/share/perl/<version>/unicore]
##
## Each map property becomes a sorted table of `start shl 8 or value` entries (a value holds from
## its start to the next entry's start) and a list of value names.

import std/[os, strutils, algorithm, tables, sequtils]

proc findUnicore(): string =
  if paramCount() >= 1: return paramStr(1)
  for d in walkDirs("/usr/share/perl/*/unicore"): return d
  for d in walkDirs("/usr/lib/x86_64-linux-gnu/perl-base/unicore"): return d
  quit "unicore not found; pass its path"

let root = findUnicore()

proc body(path: string): seq[string] =
  var inside = false
  for line in lines(path):
    if line.startsWith("return <<'END'"):
      inside = true
      continue
    if line == "END": break
    if inside and line.len > 0 and not line.startsWith("#"): result.add line

proc missing(path: string): string =
  for line in lines(path):
    if "{'missing'}" in line:
      let a = line.find('\'', line.find("= ") )
      let b = line.find('\'', a + 1)
      return line[a + 1 ..< b]

type Seg = tuple[lo, hi: int, val: string]

proc mapProperty(file: string): (seq[Seg], string) =
  let path = root / file
  var segs: seq[Seg]
  for line in body(path):
    let parts = line.split('\t')
    let lo = parseHexInt(parts[0])
    let hi = if parts[1].len > 0: parseHexInt(parts[1]) else: lo
    segs.add (lo, hi, parts[2])
  segs.sort(proc(a, b: Seg): int = cmp(a.lo, b.lo))
  (segs, missing(path))

proc binaryProperty(file: string): seq[(int, int)] =
  ## Inversion list → inclusive ranges.
  let b = body(root / file)
  var nums: seq[int]
  for line in b:
    if line.startsWith("V"): continue
    for t in line.splitWhitespace: nums.add parseInt(t)
  var i = 0
  while i < nums.len:
    let lo = nums[i]
    let hi = if i + 1 < nums.len: nums[i + 1] - 1 else: 0x10FFFF
    result.add (lo, hi)
    i += 2

var output = """## Unicode character data (UCD 15.0) for the type engine. Generated by `tools/ucdgen.nim` from the
## Unicode Character Database (Unicode License v3, https://www.unicode.org/license.txt) as shipped
## in Perl's `unicore`. Do not edit.
##
## Map tables: entries `start shl 8 or value`, sorted; a value holds up to the next entry's start.

"""

proc emitMap(name: string; segs: seq[Seg]; missingVal: string; names: var seq[string]) =
  ## Writes `<name>Names` and `<name>Table`.
  if missingVal notin names: names.insert(missingVal, 0)
  for s in segs:
    if s.val notin names: names.add s.val
  var entries: seq[uint32]
  var cp = 0
  var last = -1
  proc put(start, v: int) =
    if v != last:
      entries.add uint32(start shl 8 or v)
      last = v
  let miss = names.find(missingVal)
  for s in segs:
    if s.lo > cp: put(cp, miss)
    put(s.lo, names.find(s.val))
    cp = s.hi + 1
  if cp <= 0x10FFFF: put(cp, miss)
  doAssert names.len < 256
  output.add "const " & name & "Names* = [" & names.mapIt("\"" & it & "\"").join(", ") & "]\n"
  output.add "const " & name & "Table*: array[" & $entries.len & ", uint32] = [\n"
  var line = "  "
  for i, e in entries:
    let s = "0x" & toHex(e, 8) & "'u32" & (if i + 1 < entries.len: ", " else: "")
    if line.len + s.len > 110:
      output.add line.strip(leading = false) & "\n"
      line = "  "
    line.add s
  output.add line & "]\n\n"

proc emitRanges(name: string; ranges: seq[(int, int)]) =
  output.add "const " & name & "*: array[" & $(ranges.len * 2) & ", uint32] = [\n"
  var line = "  "
  for i, r in ranges:
    let s = "0x" & toHex(r[0], 6) & "'u32, 0x" & toHex(r[1], 6) & "'u32" & (if i + 1 < ranges.len: ", " else: "")
    if line.len + s.len > 110:
      output.add line.strip(leading = false) & "\n"
      line = "  "
    line.add s
  output.add line & "]\n\n"

# Fixed value orders the engine refers to by ordinal.
var gc = @["Cn", "Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Mc", "Me", "Nd", "Nl", "No", "Pc", "Pd", "Ps", "Pe",
           "Pi", "Pf", "Po", "Sm", "Sc", "Sk", "So", "Zs", "Zl", "Zp", "Cc", "Cf", "Cs", "Co"]
var lb = @["XX", "BK", "CR", "LF", "CM", "NL", "SG", "WJ", "ZW", "GL", "SP", "ZWJ", "B2", "BA", "BB", "HY",
           "CB", "CL", "CP", "EX", "IN", "NS", "OP", "QU", "IS", "NU", "PO", "PR", "SY", "AI", "AL", "CJ",
           "EB", "EM", "H2", "H3", "HL", "ID", "JL", "JV", "JT", "RI", "SA"]
var gcb = @["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator", "Prepend",
            "SpacingMark", "L", "V", "T", "LV", "LVT"]
var bc = @["L", "R", "AL", "EN", "ES", "ET", "AN", "CS", "NSM", "BN", "B", "S", "WS", "ON", "LRE", "LRO",
           "RLE", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI"]
var ea = @["N", "A", "F", "H", "Na", "W"]
var bpt = @["n", "o", "c"]

block:
  let (s, m) = mapProperty("To/Gc.pl")
  emitMap("gc", s, m, gc)
block:
  let (s, m) = mapProperty("To/Lb.pl")
  emitMap("lb", s, m, lb)
block:
  var (s, m) = mapProperty("To/GCB.pl")
  for x in s.mitems:
    if x.val == "ExtPict_XX": x.val = "Other"
  emitMap("gcb", s, m, gcb)
block:
  let (s, m) = mapProperty("To/Bc.pl")
  emitMap("bc", s, m, bc)
block:
  let (s, m) = mapProperty("To/Ea.pl")
  emitMap("ea", s, m, ea)
block:
  var (s, m) = mapProperty("To/Bpt.pl")
  for x in s.mitems: x.val = x.val.toLowerAscii
  emitMap("bpt", s, m.toLowerAscii, bpt)
block:
  # Scripts: long names, plus their ISO 15924 codes from UCD.pl's 'sc=<name>' => '<code>' aliases.
  let (s, m) = mapProperty("To/Sc.pl")
  var names = @[m, "Common", "Inherited"]
  emitMap("sc", s, m, names)
  var codes = initTable[string, string]()
  for line in lines(root / "UCD.pl"):
    if line.startsWith("'sc=") and "' => '" in line and "/" notin line and "#" notin line:
      let k = line[4 ..< line.find('\'', 4)]
      let v = line[line.find("=> '") + 4 ..< line.rfind('\'')]
      if v.len == 4 and k notin codes: codes[k] = v
  var iso: seq[string]
  for n in names:
    let key = n.toLowerAscii.replace("_", "")
    let c = codes.getOrDefault(key, "zzzz")
    iso.add c[0].toUpperAscii & c[1 .. 3]
  output.add "const scCodes* = [" & iso.mapIt("\"" & it & "\"").join(", ") & "]\n  ## ISO 15924 code per `scNames` entry.\n\n"
block:
  # Bidi mirroring glyph (code point pairs).
  var pairs: seq[(int, int)]
  for line in body(root / "To/Bmg.pl"):
    let p = line.split('\t')
    pairs.add (parseHexInt(p[0]), parseHexInt(p[2]))
  output.add "const bmgPairs*: array[" & $(pairs.len * 2) & ", uint32] = [\n"
  var line = "  "
  for i, r in pairs:
    let s = "0x" & toHex(r[0], 6) & "'u32, 0x" & toHex(r[1], 6) & "'u32" & (if i + 1 < pairs.len: ", " else: "")
    if line.len + s.len > 110:
      output.add line.strip(leading = false) & "\n"
      line = "  "
    line.add s
  output.add line & "]\n\n"
block:
  # Canonical combining class (non-zero ranges).
  var segs: seq[(int, int, int)]
  for line in body(root / "CombiningClass.pl"):
    let p = line.split('\t')
    let lo = parseHexInt(p[0])
    let hi = if p[1].len > 0: parseHexInt(p[1]) else: lo
    segs.add (lo, hi, parseInt(p[2]))
  output.add "const cccRanges*: array[" & $(segs.len * 3) & ", uint32] = [\n"
  var line = "  "
  for i, r in segs:
    let s = "0x" & toHex(r[0], 6) & "'u32, 0x" & toHex(r[1], 6) & "'u32, " & $r[2] & "'u32" & (if i + 1 < segs.len: ", " else: "")
    if line.len + s.len > 110:
      output.add line.strip(leading = false) & "\n"
      line = "  "
    line.add s
  output.add line & "]\n\n"
block:
  # Canonical decompositions (one level): cp, first, second (0 for singletons).
  var rows: seq[(int, int, int)]
  for line in body(root / "Decomposition.pl"):
    let p = line.split('\t')
    if p[2].startsWith("<"): continue
    let lo = parseHexInt(p[0])
    let hi = if p[1].len > 0: parseHexInt(p[1]) else: lo
    let d = p[2].splitWhitespace.mapIt(parseHexInt(it))
    for cp in lo .. hi:
      rows.add (cp, d[0], if d.len > 1: d[1] else: 0)
  output.add "const decompositions*: array[" & $(rows.len * 3) & ", uint32] = [\n"
  var line = "  "
  for i, r in rows:
    let s = "0x" & toHex(r[0], 6) & "'u32, 0x" & toHex(r[1], 6) & "'u32, 0x" & toHex(r[2], 6) & "'u32" & (if i + 1 < rows.len: ", " else: "")
    if line.len + s.len > 110:
      output.add line.strip(leading = false) & "\n"
      line = "  "
    line.add s
  output.add line & "]\n\n"

block:
  # Arabic joining: Joining_Type, with the Syriac Alaph and Dalath/Rish groups as their own values.
  var (s, m) = mapProperty("To/Jt.pl")
  var groups: seq[Seg]
  for line in body(root / "To/Jg.pl"):
    let p = line.split('\t')
    if p[2] in ["Alaph", "Dalath_Rish"]:
      let lo = parseHexInt(p[0])
      groups.add (lo, (if p[1].len > 0: parseHexInt(p[1]) else: lo), p[2])
  var merged: seq[Seg]
  for x in s:
    var cp = x.lo
    while cp <= x.hi:
      var v = x.val
      for g in groups:
        if cp >= g.lo and cp <= g.hi: v = g.val
      if merged.len > 0 and merged[^1].val == v and merged[^1].hi == cp - 1: merged[^1].hi = cp
      else: merged.add (cp, cp, v)
      inc cp
  var jt = @["U", "L", "R", "D", "Alaph", "Dalath_Rish", "T", "C"]
  emitMap("jt", merged, m, jt)

emitRanges("compositionExclusions", binaryProperty("lib/CompEx/Y.pl"))
emitRanges("extendedPictographic", binaryProperty("lib/ExtPict/Y.pl"))
emitRanges("defaultIgnorable", binaryProperty("lib/DI/Y.pl"))
emitRanges("emojiPresentation", binaryProperty("lib/EPres/Y.pl"))

let dest = currentSourcePath().parentDir.parentDir / "src/photocraft/text/ucd_data.nim"
createDir(dest.parentDir)
writeFile(dest, output)
echo "wrote ", dest, " (", output.len, " bytes)"
